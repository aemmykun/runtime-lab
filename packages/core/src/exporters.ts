import { PROVIDERS } from './providers.js';
import type { JsonValue, MockHandler, ProviderId, RunConfig, ToolDefinition } from './types.js';

export type ExportTarget = 'typescript-openai' | 'typescript-ai-sdk' | 'python';

export const EXPORT_TARGETS: Array<{ id: ExportTarget; label: string; filename: string }> = [
  { id: 'typescript-openai', label: 'TypeScript (official SDK)', filename: 'run.ts' },
  { id: 'typescript-ai-sdk', label: 'TypeScript (Vercel AI SDK generateText)', filename: 'run-ai-sdk.ts' },
  { id: 'python', label: 'Python (official SDK)', filename: 'run.py' },
];

/** OpenAI-compatible base URL each provider exposes (Gemini via its OpenAI-compatible endpoint). */
function openAICompatBase(provider: ProviderId): string | undefined {
  switch (provider) {
    case 'openai':
      return undefined;
    case 'gemini':
      return 'https://generativelanguage.googleapis.com/v1beta/openai/';
    default:
      return PROVIDERS[provider].baseUrl;
  }
}

const js = (v: unknown, indent = 2) => JSON.stringify(v, null, indent);
const pyStr = (s: string) => JSON.stringify(s); // JSON strings are valid Python string literals

function pyLiteral(v: unknown, level = 0): string {
  const pad = '    '.repeat(level + 1);
  const end = '    '.repeat(level);
  if (v === null || v === undefined) return 'None';
  if (v === true) return 'True';
  if (v === false) return 'False';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'string') return pyStr(v);
  if (Array.isArray(v)) return v.length ? `[\n${v.map((x) => pad + pyLiteral(x, level + 1)).join(',\n')},\n${end}]` : '[]';
  const entries = Object.entries(v as Record<string, unknown>);
  return entries.length ? `{\n${entries.map(([k, x]) => `${pad}${pyStr(k)}: ${pyLiteral(x, level + 1)}`).join(',\n')},\n${end}}` : '{}';
}

function mockSummary(m: MockHandler): JsonValue {
  if (m.type === 'static') return m.result;
  if (m.type === 'match') return m.default ?? (m.cases[0]?.result ?? null);
  return { error: m.message };
}

function header(config: RunConfig, lang: 'ts' | 'py'): string {
  const c = lang === 'ts' ? '//' : '#';
  const env = PROVIDERS[config.provider].keyEnv;
  return [
    `${c} Generated by Runtime Lab from a recorded run.`,
    `${c} Provider: ${PROVIDERS[config.provider].label}, model: ${config.model}`,
    `${c} The API key is read from the ${env} environment variable. Never hard-code keys.`,
    config.tools?.length ? `${c} Tool results below are the Runtime Lab JSON mocks. Replace them with real implementations.` : '',
  ]
    .filter(Boolean)
    .join('\n');
}

function openAIMessages(config: RunConfig): Array<{ role: string; content: string }> {
  return [...(config.system ? [{ role: 'system', content: config.system }] : []), ...config.messages.map((m) => ({ role: m.role, content: m.content }))];
}

function openAITools(tools: ToolDefinition[]) {
  return tools.map((t) => ({ type: 'function', function: { name: t.name, description: t.description ?? '', parameters: t.parameters } }));
}

function tsOpenAI(config: RunConfig): string {
  const env = PROVIDERS[config.provider].keyEnv;
  const tools = config.tools ?? [];
  if (config.provider === 'anthropic') {
    const params: Record<string, unknown> = {
      model: config.model,
      max_tokens: config.maxTokens ?? 1024,
      ...(config.system ? { system: config.system } : {}),
      messages: config.messages,
      ...(tools.length ? { tools: tools.map((t) => ({ name: t.name, description: t.description ?? '', input_schema: t.parameters })) } : {}),
      ...(config.temperature !== undefined ? { temperature: config.temperature } : {}),
    };
    return `${header(config, 'ts')}
// npm install @anthropic-ai/sdk
import Anthropic from '@anthropic-ai/sdk';

const client = new Anthropic({ apiKey: process.env.${env} });

const message = await client.messages.create(${js(params)});

console.log(message.content);
`;
  }
  const base = openAICompatBase(config.provider);
  const params: Record<string, unknown> = {
    model: config.model,
    messages: openAIMessages(config),
    ...(tools.length ? { tools: openAITools(tools) } : {}),
    ...(config.temperature !== undefined ? { temperature: config.temperature } : {}),
    ...(config.maxTokens !== undefined ? { [config.provider === 'openai' ? 'max_completion_tokens' : 'max_tokens']: config.maxTokens } : {}),
  };
  const mocks = tools.length ? `\n// Mock tool results recorded in Runtime Lab:\nconst toolMocks: Record<string, unknown> = ${js(Object.fromEntries(tools.map((t) => [t.name, mockSummary(t.mock)])))};\n` : '';
  const toolNote = tools.length
    ? `\n// If the model asked for tools, run them and send the results back in a follow-up call:\nfor (const call of completion.choices[0]?.message.tool_calls ?? []) {\n  if (call.type === 'function') console.log('tool call', call.function.name, call.function.arguments, '-> mock:', toolMocks[call.function.name]);\n}\n`
    : '';
  const keyExpr = config.provider === 'ollama' ? `process.env.${env} ?? 'ollama'` : `process.env.${env}`;
  return `${header(config, 'ts')}
// npm install openai
import OpenAI from 'openai';

const client = new OpenAI({ apiKey: ${keyExpr}${base ? `, baseURL: ${JSON.stringify(base)}` : ''} });
${mocks}
const completion = await client.chat.completions.create(${js(params)});

console.log(completion.choices[0]?.message.content);
${toolNote}`;
}

function tsAiSdk(config: RunConfig): string {
  const p = config.provider;
  const env = PROVIDERS[p].keyEnv;
  const tools = config.tools ?? [];
  let imp: string;
  let model: string;
  switch (p) {
    case 'openai':
    case 'anthropic':
    case 'groq':
    case 'mistral':
      {
        const fn = { openai: 'createOpenAI', anthropic: 'createAnthropic', groq: 'createGroq', mistral: 'createMistral' }[p];
        imp = `import { ${fn} } from '@ai-sdk/${p}';\nconst provider = ${fn}({ apiKey: process.env.${env} });`;
      }
      model = `provider(${JSON.stringify(config.model)})`;
      break;
    case 'gemini':
      imp = `import { createGoogleGenerativeAI } from '@ai-sdk/google';\nconst provider = createGoogleGenerativeAI({ apiKey: process.env.${env} });`;
      model = `provider(${JSON.stringify(config.model)})`;
      break;
    default:
      imp = `import { createOpenAICompatible } from '@ai-sdk/openai-compatible';\nconst provider = createOpenAICompatible({ name: ${JSON.stringify(p)}, baseURL: ${JSON.stringify(PROVIDERS[p].baseUrl)}, apiKey: process.env.${env} });`;
      model = `provider(${JSON.stringify(config.model)})`;
  }
  const pkg = p === 'gemini' ? '@ai-sdk/google' : ['openai', 'anthropic', 'groq', 'mistral'].includes(p) ? `@ai-sdk/${p}` : '@ai-sdk/openai-compatible';
  const toolsSrc = tools.length
    ? `  tools: {\n${tools
        .map(
          (t) =>
            `    ${JSON.stringify(t.name)}: tool({\n      description: ${JSON.stringify(t.description ?? '')},\n      inputSchema: jsonSchema(${js(t.parameters, 2).replace(/\n/g, '\n      ')}),\n      // Mock result recorded in Runtime Lab. Replace with a real implementation.\n      execute: async () => (${js(mockSummary(t.mock), 2).replace(/\n/g, '\n      ')}),\n    }),`,
        )
        .join('\n')}\n  },\n  stopWhen: isStepCount(${config.maxTurns ?? 5}),\n`
    : '';
  const imports = tools.length ? `import { generateText, tool, jsonSchema, isStepCount } from 'ai';` : `import { generateText } from 'ai';`;
  const prompt =
    config.messages.length === 1 && config.messages[0]!.role === 'user'
      ? `  prompt: ${JSON.stringify(config.messages[0]!.content)},\n`
      : `  messages: ${js(config.messages, 2).replace(/\n/g, '\n  ')},\n`;
  return `${header(config, 'ts')}
// npm install ai ${pkg}
${imports}
${imp}

const result = await generateText({
  model: ${model},
${config.system ? `  instructions: ${JSON.stringify(config.system)},\n` : ''}${prompt}${toolsSrc}${config.temperature !== undefined ? `  temperature: ${config.temperature},\n` : ''}${config.maxTokens !== undefined ? `  maxOutputTokens: ${config.maxTokens},\n` : ''}});

console.log(result.text);
`;
}

function python(config: RunConfig): string {
  const env = PROVIDERS[config.provider].keyEnv;
  const tools = config.tools ?? [];
  if (config.provider === 'anthropic') {
    const params: Record<string, unknown> = {
      model: config.model,
      max_tokens: config.maxTokens ?? 1024,
      ...(config.system ? { system: config.system } : {}),
      messages: config.messages,
      ...(tools.length ? { tools: tools.map((t) => ({ name: t.name, description: t.description ?? '', input_schema: t.parameters })) } : {}),
      ...(config.temperature !== undefined ? { temperature: config.temperature } : {}),
    };
    return `${header(config, 'py')}
# pip install anthropic
import os
from anthropic import Anthropic

client = Anthropic(api_key=os.environ[${pyStr(env)}])

params = ${pyLiteral(params)}

message = client.messages.create(**params)
print(message.content)
`;
  }
  const base = openAICompatBase(config.provider);
  const params: Record<string, unknown> = {
    model: config.model,
    messages: openAIMessages(config),
    ...(tools.length ? { tools: openAITools(tools) } : {}),
    ...(config.temperature !== undefined ? { temperature: config.temperature } : {}),
    ...(config.maxTokens !== undefined ? { [config.provider === 'openai' ? 'max_completion_tokens' : 'max_tokens']: config.maxTokens } : {}),
  };
  const keyExpr = config.provider === 'ollama' ? `os.environ.get(${pyStr(env)}, "ollama")` : `os.environ[${pyStr(env)}]`;
  const mocks = tools.length ? `\n# Mock tool results recorded in Runtime Lab:\ntool_mocks = ${pyLiteral(Object.fromEntries(tools.map((t) => [t.name, mockSummary(t.mock)])))}\n` : '';
  const toolNote = tools.length
    ? `\n# If the model asked for tools, run them and send the results back in a follow-up call:\nfor call in completion.choices[0].message.tool_calls or []:\n    print("tool call", call.function.name, call.function.arguments, "-> mock:", tool_mocks.get(call.function.name))\n`
    : '';
  return `${header(config, 'py')}
# pip install openai
import os
from openai import OpenAI

client = OpenAI(api_key=${keyExpr}${base ? `, base_url=${pyStr(base)}` : ''})
${mocks}
params = ${pyLiteral(params)}

completion = client.chat.completions.create(**params)
print(completion.choices[0].message.content)
${toolNote}`;
}

export function exportRun(config: RunConfig, target: ExportTarget): string {
  switch (target) {
    case 'typescript-openai':
      return tsOpenAI(config);
    case 'typescript-ai-sdk':
      return tsAiSdk(config);
    case 'python':
      return python(config);
  }
}
